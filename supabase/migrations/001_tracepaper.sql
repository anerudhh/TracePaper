-- Run once in the Supabase SQL editor. Only the backend service role can access these objects.
begin;
create table if not exists public.tp_papers (
 id text primary key, name text not null, kind text not null check(kind in ('pdf','docx')),
 size bigint not null, digest text not null unique,
 status text not null check(status in ('uploading','queued','indexing','ready','failed')),
 error text, pages integer not null default 0, created timestamptz not null default now()
);
create table if not exists public.tp_chunks (
 id bigint generated by default as identity primary key,
 paper_id text not null references public.tp_papers(id) on delete cascade,
 page integer not null, text text not null,
 terms tsvector generated always as (to_tsvector('english',text)) stored
);
create index if not exists tp_chunks_terms on public.tp_chunks using gin(terms);
create index if not exists tp_chunks_paper on public.tp_chunks(paper_id);
create table if not exists public.tp_history (
 id text primary key, question text not null, result jsonb not null,
 created timestamptz not null default now()
);
create table if not exists public.tp_deleted_files(id text primary key, kind text not null);
alter table public.tp_papers enable row level security;
alter table public.tp_chunks enable row level security;
alter table public.tp_history enable row level security;
alter table public.tp_deleted_files enable row level security;
revoke all on public.tp_papers,public.tp_chunks,public.tp_history,public.tp_deleted_files from public,anon,authenticated;
grant all on public.tp_papers,public.tp_chunks,public.tp_history,public.tp_deleted_files to service_role;
grant usage,select on sequence public.tp_chunks_id_seq to service_role;

create or replace function public.tp_health() returns jsonb language sql security invoker set search_path=public as $$
 select jsonb_build_object('ready',true,'schema_version',1,'papers',(select count(*) from public.tp_papers));
$$;
create or replace function public.tp_recover() returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 update public.tp_papers set status='failed',error='Upload was interrupted. Remove this entry and upload again.' where status='uploading';
 update public.tp_papers set status='queued' where status='indexing';
 return coalesce((select jsonb_agg(id order by created,id) from public.tp_papers where status='queued'),'[]'::jsonb);
end $$;
create or replace function public.tp_get_paper(p_id text) returns jsonb language sql security invoker set search_path=public as $$
 select to_jsonb(p) from public.tp_papers p where id=p_id;
$$;
create or replace function public.tp_create_paper(p_row jsonb) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 insert into public.tp_papers(id,name,kind,size,digest,status)
 values(p_row->>'id',p_row->>'name',p_row->>'kind',(p_row->>'size')::bigint,p_row->>'digest','uploading')
 on conflict(digest) do nothing;
 return (select to_jsonb(p) from public.tp_papers p where digest=p_row->>'digest');
end $$;
create or replace function public.tp_list_papers(p_query text default '',p_limit integer default 50,p_offset integer default 0) returns jsonb language sql security invoker set search_path=public as $$
 select jsonb_build_object(
 'items',coalesce((select jsonb_agg(to_jsonb(p) order by p.created desc,p.id desc) from (select * from public.tp_papers where name ilike '%'||p_query||'%' order by created desc,id desc limit greatest(1,least(p_limit,100)) offset greatest(0,p_offset)) p),'[]'::jsonb),
 'total',(select count(*) from public.tp_papers where name ilike '%'||p_query||'%'),
 'stats',(select jsonb_build_object('papers',count(*),'pages',coalesce(sum(pages),0),'ready',count(*) filter(where status='ready')) from public.tp_papers));
$$;
create or replace function public.tp_set_status(p_id text,p_status text,p_error text default null) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 update public.tp_papers set status=p_status,error=p_error where id=p_id;
 return jsonb_build_object('ok',true);
end $$;
create or replace function public.tp_begin_index(p_id text) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 delete from public.tp_chunks where paper_id=p_id;
 update public.tp_papers set status='indexing',error=null where id=p_id;
 return jsonb_build_object('ok',true);
end $$;
create or replace function public.tp_add_chunks(p_id text,p_chunks jsonb) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 if jsonb_array_length(p_chunks)>100 then raise exception 'Too many passages in a batch';end if;
 insert into public.tp_chunks(paper_id,page,text)
 select p_id,(item->>'page')::integer,item->>'text' from jsonb_array_elements(p_chunks) item;
 return jsonb_build_object('ok',true);
end $$;
create or replace function public.tp_finish_index(p_id text,p_pages integer) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 update public.tp_papers set status='ready',error=null,pages=p_pages where id=p_id;
 return jsonb_build_object('ok',true);
end $$;
create or replace function public.tp_search(p_tokens text[],p_paper_ids text[] default '{}') returns jsonb language sql security invoker set search_path=public as $$
 with query as (select websearch_to_tsquery('english',array_to_string(p_tokens,' OR ')) as terms),
 hits as (select c.id,c.paper_id,c.page,c.text,p.name,p.kind,ts_rank_cd(c.terms,q.terms) as rank
 from public.tp_chunks c join public.tp_papers p on p.id=c.paper_id cross join query q
 where c.terms @@ q.terms and p.status='ready' and (cardinality(p_paper_ids)=0 or p.id=any(p_paper_ids))
 order by rank desc,c.id limit 24)
 select coalesce(jsonb_agg(to_jsonb(h) order by h.rank desc,h.id),'[]'::jsonb) from hits h;
$$;
create or replace function public.tp_save_answer(p_result jsonb) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 insert into public.tp_history(id,question,result) values(p_result->>'id',p_result->>'question',p_result);
 return jsonb_build_object('ok',true);
end $$;
create or replace function public.tp_history() returns jsonb language sql security invoker set search_path=public as $$
 select coalesce(jsonb_agg(to_jsonb(h) order by h.created desc,h.id desc),'[]'::jsonb) from (select id,question,created from public.tp_history order by created desc,id desc limit 50) h;
$$;
create or replace function public.tp_answer(p_id text) returns jsonb language sql security invoker set search_path=public as $$
 select result from public.tp_history where id=p_id;
$$;
create or replace function public.tp_delete_paper(p_id text) returns jsonb language plpgsql security invoker set search_path=public as $$
declare paper public.tp_papers;
begin
 select * into paper from public.tp_papers where id=p_id for update;
 if not found then return jsonb_build_object('error','missing');end if;
 if paper.status in ('uploading','queued','indexing') then return jsonb_build_object('error','busy');end if;
 delete from public.tp_history h where exists(select 1 from jsonb_array_elements(h.result->'sources') s where s->>'paper_id'=p_id);
 delete from public.tp_papers where id=p_id;
 insert into public.tp_deleted_files(id,kind) values(p_id,paper.kind) on conflict do nothing;
 return jsonb_build_object('ok',true);
end $$;
create or replace function public.tp_deleted_files() returns jsonb language sql security invoker set search_path=public as $$
 select coalesce(jsonb_agg(to_jsonb(f)),'[]'::jsonb) from public.tp_deleted_files f;
$$;
create or replace function public.tp_ack_delete(p_id text) returns jsonb language plpgsql security invoker set search_path=public as $$
begin
 delete from public.tp_deleted_files where id=p_id;return jsonb_build_object('ok',true);
end $$;

-- New functions otherwise inherit PUBLIC execution rights. Revoke them atomically.
do $$ declare f record;begin
 for f in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname = any(array['tp_health','tp_recover','tp_get_paper','tp_create_paper','tp_list_papers','tp_set_status','tp_begin_index','tp_add_chunks','tp_finish_index','tp_search','tp_save_answer','tp_history','tp_answer','tp_delete_paper','tp_deleted_files','tp_ack_delete']) loop
 execute format('revoke all on function %s from public,anon,authenticated',f.signature);
 execute format('grant execute on function %s to service_role',f.signature);
 end loop;
end $$;

-- Private originals. No public/anonymous storage policies are installed.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('tracepaper','tracepaper',false,52428800,array['application/pdf','application/vnd.openxmlformats-officedocument.wordprocessingml.document'])
on conflict(id) do update set public=false,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;
notify pgrst,'reload schema';
commit;
